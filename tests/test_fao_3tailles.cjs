    "att(dg.neck===0&&!dg.noEntry&&!dg.thick&&!dg.over,'bossage : aucune alerte');",
    "att(dg.zb===11&&dg.zt===14,'bossage : rainure de z 11 à 14 (vu '+dg.zb+' / '+dg.zt+')');",
