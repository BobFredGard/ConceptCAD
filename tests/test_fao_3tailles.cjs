    "att(g3.lc.v===2.4&&g3.dDeg.v===8&&g3.dq.v===8,'défauts 3 tailles D20 : épaisseur 2,4, col Ø8, queue Ø8 (vu '+g3.lc.v+' / '+g3.dDeg.v+' / '+g3.dq.v+')');",
