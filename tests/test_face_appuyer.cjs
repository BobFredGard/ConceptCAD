// Déplacement de face façon « Appuyer/Tirer » (V0.34.0) : les bords de la face suivent ses
// voisines (dépouille, chanfrein prolongés) et une face cylindrique change de RAYON, un cône
// coaxial (pointe de foret, fraisure) suivant le nouveau rayon. Volumes exacts attendus.
const fs=require('fs'),vm=require('vm'),path=require('path');
const ROOT=path.join(__dirname,'..');
const {loadApp}=require('./appvm.cjs');
(async()=>{
  const real=await require('./noyau.cjs').charger();
  const {ctx,sandbox}=loadApp();
  sandbox.__realOcct=real;
  vm.runInContext('occt=__realOcct;occtReady=true;',ctx);
  const R=[
    "const occFaceList=s=>occSubShapes(s,'TopAbs_FACE'),occEdgeList=s=>occSubShapes(s,'TopAbs_EDGE');",
    "const P=[];const p=s=>P.push(String(s));",
    "const f1=v=>v.map(x=>x.toFixed(2)).join('/');",
    "const vol=sh=>{const g=new occt.GProp_GProps_1();occt.BRepGProp.VolumeProperties_1(sh,g,false,false,false);const m=g.Mass();g.delete();return m;};",
    "const bb=sh=>{const b=occBoxMinMax(sh);return b.lo.concat(b.hi);};",
    "const nfaces=sh=>occFaceList(sh).length;",
    "const nsol=sh=>{let n=0;const ex=new occt.TopExp_Explorer_2(sh,occt.TopAbs_ShapeEnum.TopAbs_SOLID,occt.TopAbs_ShapeEnum.TopAbs_SHAPE);while(ex.More()){n++;ex.Next();}ex.delete();return n;};",
    "const pick=(sh,fn)=>occFaceList(sh).find(f=>{const d=occSurfDesc(f),b=occBoxMinMax(f);return fn(d,b,f);});",
    "const pnt=(x,y,z)=>new occt.gp_Pnt_3(x,y,z);",
    "const box=(x0,y0,z0,x1,y1,z1)=>new occt.BRepPrimAPI_MakeBox_3(pnt(x0,y0,z0),pnt(x1,y1,z1)).Shape();",
    "const cylZ=(x,y,z,r,h)=>new occt.BRepPrimAPI_MakeCylinder_3(new occt.gp_Ax2_3(pnt(x,y,z),new occt.gp_Dir_4(0,0,1)),r,h).Shape();",
    "const prismXZ=(pts,ly)=>{const pg=new occt.BRepBuilderAPI_MakePolygon_1();pts.forEach(q=>pg.Add_1(pnt(q[0],0,q[1])));pg.Close();",
    "  const f=new occt.BRepBuilderAPI_MakeFace_15(pg.Wire(),true).Face();return new occt.BRepPrimAPI_MakePrism_1(f,new occt.gp_Vec_4(0,ly,0),false,true).Shape();};",
    "const ATT=[];",
    "const run=(name,sh,sel,dist,expect)=>{",
    "  const f=pick(sh,sel);",
    "  if(!f){p(name+' : face non trouvée');ATT.push(name+' : face non trouvée');return;}",
    "  const w=[];const t0=Date.now();",
    "  let r;try{r=occMoveFaceOnce(sh,f,dist,w);}catch(e){p(name+' : ERREUR '+(e.message||e));ATT.push(name+' : '+(e.message||e));return;}",
    "  const v=vol(r);",
    "  if(expect!=null&&Math.abs(v-expect)>=0.5)ATT.push(name+' d='+dist+' : volume '+v.toFixed(1)+' au lieu de '+expect.toFixed(1));",
    "  if(expect!=null&&w.length)ATT.push(name+' d='+dist+' : alerte '+w.join(' | '));",
    "  if(nsol(r)!==1||!occCoqueValide(r))ATT.push(name+' d='+dist+' : solide invalide ou multiple');",
    "  p(name+' d='+dist+' : bb '+f1(bb(r))+' vol '+v.toFixed(1)+(expect!=null?' (attendu '+expect.toFixed(1)+(Math.abs(v-expect)<0.5?' OK':' ✗')+')':'')+' faces '+nfaces(r)+' solides '+nsol(r)+' valide '+occCoqueValide(r)+' '+(Date.now()-t0)+'ms'+(w.length?' ! '+w.join(' | '):''));",
    "};",
    "// A. tronc de pyramide (profil XZ trapèze, extrudé Y) : dessus z=40, flancs à 1/4",
    "{",
    "  const sh=prismXZ([[0,0],[100,0],[90,40],[10,40]],60);",
    "  const top=(d,b)=>d.k==='pl'&&Math.abs(b.lo[2]-40)<1e-6&&Math.abs(b.hi[2]-40)<1e-6;",
    "  // aire trapèze: z de 0 à Z, largeur 100-z/2",
    "  const V=Z=>60*(100*Z-Z*Z/4);",
    "  run('A tronc dessus',sh,top,10,V(50));",
    "  run('A tronc dessus',sh,top,-10,V(30));",
    "}",
    "// F. chanfrein : profil (0,0),(100,0),(100,30),(90,40),(0,40)",
    "{",
    "  const sh=prismXZ([[0,0],[100,0],[100,30],[90,40],[0,40]],60);",
    "  const top=(d,b)=>d.k==='pl'&&Math.abs(b.lo[2]-40)<1e-6&&Math.abs(b.hi[2]-40)<1e-6;",
    "  const V=Z=>60*(100*Z-(Z-30)*(Z-30)/2);",
    "  run('F chanfrein dessus',sh,top,5,V(45));",
    "  run('F chanfrein dessus',sh,top,-5,V(35));",
    "}",
    "// B. plaque percée",
    "{",
    "  const sh=occCut(box(0,0,0,100,60,10),cylZ(50,30,-1,5,12));",
    "  const hole=d=>d.k==='cy';",
    "  run('B trou',sh,hole,2,6000*10/10*1-Math.PI*9*10+ (100*60*10-6000)); // r3",
    "  run('B trou',sh,hole,-2,100*60*10-Math.PI*49*10);",
    "}",
    "// C. bossage",
    "{",
    "  const sh=occUnify(occFuse(box(0,0,0,60,60,10),cylZ(30,30,10,10,20)));",
    "  const boss=d=>d.k==='cy';",
    "  run('C bossage',sh,boss,3,36000+Math.PI*169*20);",
    "  run('C bossage',sh,boss,-3,36000+Math.PI*49*20);",
    "}",
    "// D. trou borgne à pointe 118°",
    "{",
    "  const r=5,ha=59*Math.PI/180,hc=r/Math.tan(ha);",
    "  const cone=new occt.BRepPrimAPI_MakeCone_3(new occt.gp_Ax2_3(pnt(30,30,15-hc),new occt.gp_Dir_4(0,0,1)),0,r,hc).Shape();",
    "  const tool=occFuse(cylZ(30,30,15,r,16),cone);",
    "  const sh=occCut(box(0,0,0,60,60,30),tool);",
    "  const hole=d=>d.k==='cy';",
    "  const Vh=R=>{const h=R/Math.tan(ha);return Math.PI*R*R*(30-(15-hc)-h)+Math.PI*R*R*h/3;};// pointe gardée au même sommet",
    "  run('D borgne',sh,hole,-2,54000*1.0*30/30*1+0-Vh(7)+0*0+ (60*60*30-54000));",
    "  run('D borgne',sh,hole,1,60*60*30-Vh(4));",
    "}",
    "// E. dessus en L",
    "{",
    "  const sh=occUnify(occFuse(box(0,0,0,100,30,20),box(0,0,0,30,80,20)));",
    "  const top=(d,b)=>d.k==='pl'&&Math.abs(b.lo[2]-20)<1e-6&&Math.abs(b.hi[2]-20)<1e-6;",
    "  run('E L dessus',sh,top,5,(3000+1500)*25);",
    "}",
    "// G. bossage à dessus incliné : cylindre r10 coupé par un plan incliné",
    "{",
    "  const base=occUnify(occFuse(box(0,0,0,60,60,10),cylZ(30,30,10,10,30)));",
    "  const cutter=prismXZ([[0,30],[60,20],[60,60],[0,60]],60);",
    "  const sh=occCut(base,cutter);",
    "  const boss=d=>d.k==='cy';",
    "  run('G bossage incliné',sh,boss,2,36000+Math.PI*144*15);",
    "}",
    "// H. fraisure 90° en haut d'un trou r5 dans une plaque 20 : cône r10 au dessus (z=20) -> r5 à z=15",
    "{",
    "  const cone=new occt.BRepPrimAPI_MakeCone_3(new occt.gp_Ax2_3(pnt(30,30,15),new occt.gp_Dir_4(0,0,1)),5,10,5).Shape();",
    "  const sh=occCut(box(0,0,0,60,60,20),occFuse(cylZ(30,30,-1,5,17),cone));",
    "  const hole=d=>d.k==='cy';",
    "  const V=R=>Math.PI*R*R*(15+(R-5))+Math.PI*(10-R)*(R*R+R*10+100)/3;",
    "  run('H fraisure',sh,hole,-2,72000-V(7));",
    "  run('H fraisure',sh,hole,1,72000-V(4));",
    "}",
    "// I. dessus bordé d'un congé R5 (arête y=60, z=40)",
    "{",
    "  let sh=box(0,0,0,100,60,40);",
    "  const mk=new occt.BRepFilletAPI_MakeFillet(sh,occt.ChFi3d_FilletShape.ChFi3d_Rational);",
    "  occEdgeList(sh).forEach(e=>{const b=occBoxMinMax(e);if(b.lo[1]>59.9&&b.lo[2]>39.9)mk.Add_2(5,occt.TopoDS.Edge_1(e));});",
    "  mk.Build();sh=mk.Shape();",
    "  const top=(d,b)=>d.k==='pl'&&Math.abs(b.lo[2]-40)<1e-6&&Math.abs(b.hi[2]-40)<1e-6;",
    "  run('I congé dessus',sh,top,5,null);",
    "  const fil=d=>d.k==='cy';",
    "  run('I congé rayon',sh,fil,2,null);",
    "}",
    "// J. rainure oblongue (deux demi-cylindres + plans tangents) : élargir l'extrémité",
    "{",
    "  const slot=occFuse(occFuse(cylZ(20,30,-1,5,12),cylZ(60,30,-1,5,12)),box(20,25,-1,60,35,11));",
    "  const sh=occUnify(occCut(box(0,0,0,100,60,10),slot));",
    "  const end=(d,b)=>d.k==='cy'&&b.hi[0]<21;",
    "  run('J rainure bout',sh,end,-1,null);",
    "}",
    "if(ATT.length){p('');p('ECHECS ('+ATT.length+') :');ATT.forEach(m=>p('  ✗ '+m));}else{p('');p('TOUT EST CONFORME');}",
    "return P.join(String.fromCharCode(10));"
  ].join('\n');
  const r=await vm.runInContext('(async()=>{'+R+'})()',ctx,{filename:'face_appuyer.js'});
  console.log(r);
  process.exit(/ECHECS|✗/.test(r)?1:0);
})().catch(e=>{console.error('ECHEC',String((e&&e.message)||e).slice(0,500));process.exit(1);});
